export type CoverageCity = { all: boolean; areas: string[] };
export type CoverageGovernorate = { all: boolean; cities: Record<string,CoverageCity> };
export type CompanyCoverage = Record<string,CoverageGovernorate>;
export interface CoveredCompany {
  governorates: string[];
  coverage?: CompanyCoverage | undefined;
}
const catalogByGovernorate = new Map<string,(typeof EGYPT_COVERAGE_CATALOG)[number]>(
  EGYPT_COVERAGE_CATALOG.map(g=>[g.id,g]));
export function normalizeCoverageSearch(input: unknown): string {
  return String(input??"").trim().toLowerCase()
    .replace(/[\u064b-\u065f\u0670\u0640]/g,"").replace(/[أإآ]/g,"ا").replace(/ة/g,"ه")
    .replace(/[\s\-_]+/g,"");
}
export function governorateFromText(input: unknown): string | null {
  const n=normalizeCoverageSearch(input);
  for(const g of EGYPT_COVERAGE_CATALOG){
    if(normalizeCoverageSearch(g.id)===n || normalizeCoverageSearch(g.ar)===n ||
      normalizeCoverageSearch("محافظة "+g.ar)===n ||
      normalizeCoverageSearch(g.id+" governorate")===n) return g.id;
  }
  return null;
}
export function validateCompanyCoverage(company: CoveredCompany): void {
  if (!Array.isArray(company.governorates) || company.governorates.length>27 ||
      new Set(company.governorates).size!==company.governorates.length ||
      company.governorates.some(name=>!catalogByGovernorate.has(name))) {
    throw new Error("Choose governorates from the official selection list.");
  }
  if(company.coverage===undefined)return; // legacy company settings remain compatible.
  const selected=Object.keys(company.coverage);
  if(!selected.length || selected.length!==company.governorates.length ||
    selected.some(g=>!company.governorates.includes(g))) {
    throw new Error("Select at least one governorate; coverage and selected governorates must match.");
  }
  for(const [govId,node] of Object.entries(company.coverage)){
    const gov=catalogByGovernorate.get(govId);
    if(!gov || !node || typeof node.all!=="boolean" || !node.cities || Array.isArray(node.cities))
      throw new Error("Invalid governorate coverage selection.");
    if(node.all && Object.keys(node.cities).length)throw new Error("Entire-governorate coverage cannot also set cities.");
    if(!node.all && !Object.keys(node.cities).length)throw new Error("Select cities or choose the entire governorate.");
    for(const [cityId,cityNode] of Object.entries(node.cities)){
      const city=gov.cities.find(c=>c.id===cityId);
      if(!city || typeof cityNode.all!=="boolean" || !Array.isArray(cityNode.areas) ||
        new Set(cityNode.areas).size!==cityNode.areas.length)
        throw new Error("Choose cities and areas from the selection list.");
      if(cityNode.all && cityNode.areas.length)throw new Error("Entire-city coverage cannot also set areas.");
      if(!cityNode.all && !cityNode.areas.length)throw new Error("Select areas or choose the entire city.");
      if(cityNode.areas.some(areaId=>!city.areas.some(a=>a.id===areaId)))
        throw new Error("Unknown area in shipping coverage.");
    }
  }
}
function matchesPart(input: unknown, id:string, en:string, ar:string):boolean{
  const n=normalizeCoverageSearch(input);
  return Boolean(n) && [id,en,ar].some(x=>normalizeCoverageSearch(x)===n);
}
// No free-text guessing: narrow coverage without an unambiguous city/area is not eligible.
export function isCompanyAddressCovered(company: CoveredCompany, governorate:unknown, city?:unknown, area?:unknown):boolean {
  const g=governorateFromText(governorate);
  if(!g)return false;
  if(company.coverage===undefined) {
    return company.governorates.length===0 || company.governorates.includes(g);
  }
  const scope=company.coverage[g];if(!scope)return false;
  if(scope.all)return true;
  const gov=catalogByGovernorate.get(g)!;
  // Existing orders may store a city or area in the free-text 'area' field.
  const matched=gov.cities.filter(x=>matchesPart(city,x.id,x.en,x.ar) || matchesPart(area,x.id,x.en,x.ar));
  if(matched.length!==1)return false;
  const chosenCity=matched[0], selected=scope.cities[chosenCity.id];
  if(!selected)return false;
  if(selected.all)return true;
  return chosenCity.areas.some(a=>selected.areas.includes(a.id) &&
    (matchesPart(area,a.id,a.en,a.ar) || matchesPart(city,a.id,a.en,a.ar)));
}
